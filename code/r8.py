#!/usr/bin/env python3
import os

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")
import argparse
import json
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import asd
import r7

NEW = {"nohome": "r8_ppi_mimiciv_nohome.sql", "ordnohome": "r8_ppi_mimiciv_ordnohome.sql"}
ADDED_VS = {"nohome": "c2m", "ordnohome": "ord"}
HOME_LINE = "\n    AND f.hadm_id NOT IN (SELECT hadm_id FROM home)"
ORD_LIKE = ("ord", "ordnohome")
TITLES = {"nohome": "R8 variant 4d: MIMIC-IV PPI comparison without the home-medication exclusion (eICU could not apply it)",
          "ordnohome": "R8 variant 4e: MIMIC-IV PPI comparison with time zero, arm and route from orders and without the home-medication exclusion"}
LAB = {"c2m": "Gate definition (by administration; use before admission excluded)", "ord": "4b by orders (R7)", "nohome": "4d use before admission not excluded",
       "ordnohome": "4e by orders and use before admission not excluded (the eICU way)"}
E_KEY = "c2e"
OUTS = ("m0_primary", "m0_negctl")

r7.VARIANT_FILES.update(NEW)
r7.VARIANTS.update({k: ("m", 2) for k in NEW})
_r7_variant_statements = r7.variant_statements


def variant_statements(P, name):
    st = _r7_variant_statements(P, name)
    if name == "ordnohome":
        files = asd.plist([r7.pf(P, "m", f"{name}_cohort")])
        st.append(("route", r7.ROUTE_ORD.format(files=files), r7.pf(P, "m", f"{name}_route")))
    return st


def load_variant(P, name):
    db, comparison = r7.VARIANTS[name]
    co = asd.read_pq(r7.pf(P, db, f"{name}_cohort"))
    flow = {"eligible": len(co), "A": int((co["arm"] == "A").sum()), "B": int((co["arm"] == "B").sum()), "other": int(co["arm"].isna().sum())}
    df = co[co["arm"].isin(["A", "B"])].copy()
    for part in ("covars", "follow", "outcome"):
        df = df.merge(asd.read_pq(r7.pf(P, db, f"{name}_{part}")), on="stay_id", how="left", validate="one_to_one")
    if name in ORD_LIKE:
        df = df.merge(asd.read_pq(r7.pf(P, db, f"{name}_route")), on="stay_id", how="left", validate="one_to_one")
        df["route"] = df["route_ord"].fillna("UNK")
    df["t_dev"] = np.nan
    keep = asd.overlap_keep(df, db == "e")
    flow["outside_overlap"] = int((~keep).sum())
    df = df[keep].sort_values("stay_id", kind="mergesort").reset_index(drop=True)
    flow["analysis_A"], flow["analysis_B"] = int((df["arm"] == "A").sum()), int((df["arm"] == "B").sum())
    return df, flow


r7.variant_statements = variant_statements
r7.load_variant = load_variant


def variant_sql(name):
    b = r7.cte_blocks(asd.gate_body(2, "m"))
    if name == "ordnohome":
        b["asadm"] = r7.ASADM_ORD
        b["cand"] = r7.must_replace(b["cand"], r7.WASH_ADM, r7.WASH_ORD)
    b["cand"] = r7.must_replace(b["cand"], HOME_LINE, "")
    head = (f"-- {TITLES[name]}\n-- Generated by r8.py make-variants from the locked ppi_mimiciv.sql (revision R8, "
            "SAP_addendum_R8.md v1.0); do not edit by hand.\n")
    return head + "WITH " + ",\n".join(b.values()) + "\n"


def make_variants(args):
    for name, f in NEW.items():
        txt = variant_sql(name)
        path = os.path.join(asd.SQL_DIR, f)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != txt:
            open(path, "w", encoding="utf-8").write(txt)
        print(f"{f}: {'unchanged' if old == txt else 'written'}", flush=True)


def selftest(args):
    res = []

    def check(name, ok):
        res.append(bool(ok))
        print(f"{'PASS' if ok else 'FAIL'} | {name}", flush=True)

    body = {k: r7.sql_body_text(variant_sql(k)) for k in NEW}
    for name in NEW:
        check(f"{name}: generation is deterministic", variant_sql(name) == variant_sql(name))
        cand = r7.cte_blocks(body[name])["cand"]
        check(f"{name}: home-medication exclusion removed; washout, delirium, bleeding and infusion exclusions kept",
              "FROM home" not in cand and "FROM asadm a" in cand and "FROM cam c" in cand and "FROM gib" in cand and "FROM ppi_inf p" in cand)
    gate = asd.gate_body(2, "m")
    check("nohome: the gate SQL minus the home line, nothing else changed", r7.ws(body["nohome"]) == r7.ws(gate.replace(HOME_LINE, "", 1)))
    ordb = r7.sql_body_text(r7.variant_sql("ord"))
    check("ordnohome: R7 variant 4b minus the home line, nothing else changed", r7.ws(body["ordnohome"]) == r7.ws(ordb.replace(HOME_LINE, "", 1)))
    st = {k: [p for p, _, _ in variant_statements("/x", k)] for k in ("ord", "nohome", "ordnohome")}
    check("route from the time-zero order for 4b and 4e only", "route" in st["ord"] and "route" in st["ordnohome"] and "route" not in st["nohome"])
    check("r7 uses the R8 statement and loader functions", r7.variant_statements is variant_statements and r7.load_variant is load_variant)
    check("variant keys: m0 primary and negative control only", all(r7.names_for(k) == list(OUTS) for k in NEW))
    print(f"{sum(res)}/{len(res)} passed")
    sys.exit(0 if all(res) else 1)


def variant(args):
    t0 = time.time()
    P = os.path.expanduser(args.private)
    con = asd.connect_slim(P, "m")
    for part, sql, path in variant_statements(P, args.name):
        asd.write_pq(con, sql, path)
        asd.status(f"{os.path.basename(path)} written", t0)
    asd.log_run(args.results, f"r8 variant --name {args.name}: ok ({time.time() - t0:.0f} s)")


def estimate(args):
    t0 = time.time()
    P = os.path.expanduser(args.private)
    for key in NEW:
        df, flow, dd = r7.load_dd(P, key)
        cache = {}
        res = r7.analyses(dd, key, cache)
        desc = {"balance": {m: r7.balance(d, cache, m) for m, d in dd.items()}}
        json.dump({"flow": flow, "res": asd.to_json(res), "desc": asd.to_json(desc)}, open(os.path.join(P, f"r8_est_{key}.json"), "w"))
        np.savez(os.path.join(P, f"r7_cache_{key}.npz"), **{k.replace(":", "__"): v for k, v in cache.items()})
        asd.status(f"r8 estimate {key} done", t0)
    asd.log_run(args.results, f"r8 estimate: ok ({time.time() - t0:.0f} s)")


def report(args):
    P, R = os.path.expanduser(args.private), os.path.expanduser(args.results)
    est = {k: json.load(open(os.path.join(P, f"r8_est_{k}.json"))) for k in NEW}
    for k in ("c2m", "ord", E_KEY):
        est[k] = json.load(open(os.path.join(P, f"r7_est_{k}.json")))
    boots = {k: r7.load_boot(P, k) for k in est}
    S = {k: r7.summarise(est, boots, k) for k in est}
    e_or = S[E_KEY]["m0_primary"]["OR"]
    rows = list(LAB)
    out = {"plan": "SAP_addendum_R8.md v1.0", "boot_reps": {k: (boots[k]["n"] if boots[k] else 0) for k in NEW},
           "eicu_m0": {n: S[E_KEY][n] for n in OUTS}, "flow": {k: est[k]["flow"] for k in rows},
           "per_key": {k: {n: S[k][n] for n in OUTS} for k in rows}, "pooled": {}, "reading": {}, "knife_edge": {},
           "added": {}, "balance": {k: est[k]["desc"]["balance"]["m0"]["max_abs_smd_ow"] for k in rows}}
    for k in rows:
        for n in OUTS:
            out["pooled"][f"{k}:{n}"] = r7.pool(S[k][n], S[E_KEY][n])
    for k in NEW:
        p = S[k]["m0_primary"]
        if p.get("OR_lo") is None:
            out["reading"][k] = "no interval"
            continue
        inside = p["OR_lo"] <= e_or <= p["OR_hi"]
        out["reading"][k] = "defined the eICU way the databases agree: the disagreement comes from the population or exposure definitions" if inside else "population and exposure definitions do not explain the disagreement between the databases"
        out["knife_edge"][k] = bool(min(abs(p["OR_lo"] - e_or), abs(p["OR_hi"] - e_or)) < 0.005)
        f, g = est[k]["flow"], est[ADDED_VS[k]]["flow"]
        out["added"][k] = {"A": f["analysis_A"] - g["analysis_A"], "B": f["analysis_B"] - g["analysis_B"]}
    masked = r7.mask_tree(out)
    json.dump(asd.round_floats(masked), open(os.path.join(R, "r8.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    open(os.path.join(R, "r8.md"), "w", encoding="utf-8").write(md(masked))
    asd.log_run(args.results, "r8 report: ok")
    print("report written", flush=True)


def md(o):
    e = o["eicu_m0"]
    L = ["# Revision R8 results: the MIMIC-IV population defined the eICU way (PPI comparison)", "",
         f"Plan: {o['plan']}. Bootstrap replicates: {', '.join(f'{k} {v}' for k, v in o['boot_reps'].items())} (intervals of the gate definition and 4b from R7). "
         "Counts masked: 1–9 as <10, otherwise the nearest multiple of 5. Odds ratios PPI vs famotidine, 168 hours, overlap weighting, SAP covariates (M0). "
         f"Pooled with eICU M0: primary outcome {r7.orci(e['m0_primary'])}, negative control {r7.orci(e['m0_negctl'])}.", "",
         "| MIMIC-IV definition | Patients analysed PPI / famotidine | Primary outcome | Pooled with eICU (I²) | Negative control | Pooled with eICU (I²) | Reading (written rule) |",
         "|---|---|---|---|---|---|---|"]
    for k, t in LAB.items():
        f = o["flow"][k]
        a, b = o["per_key"][k]["m0_primary"], o["per_key"][k]["m0_negctl"]
        pa, pb = o["pooled"][f"{k}:m0_primary"], o["pooled"][f"{k}:m0_negctl"]
        L.append(f"| {t} | {f['analysis_A']} / {f['analysis_B']} | {r7.orci(a)} | {r7.orci(pa)}{r7.i2(pa)} | "
                 f"{r7.orci(b)} | {r7.orci(pb)}{r7.i2(pb)} | {o['reading'].get(k, 'reference')} |")
    L.append("")
    for k in NEW:
        ad = o["added"].get(k)
        if ad:
            L.append(f"- {LAB[k]}: compared with {LAB[ADDED_VS[k]]}, additional PPI {ad['A']}, famotidine {ad['B']} patients (taken before admission, all other criteria met)"
                     + ("; reading on the threshold (interval limit within <0.005 of the eICU point estimate)" if o["knife_edge"].get(k) else ""))
    L.append("- Largest |SMD| after overlap weighting: " + "; ".join(f"{k} {v:.3f}" for k, v in o["balance"].items()))
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    for name in ("make-variants", "selftest", "bindcheck"):
        sp.add_parser(name)
    subs = {c: sp.add_parser(c) for c in ("variant", "estimate", "boot", "report")}
    for s in subs.values():
        s.add_argument("--private", required=True)
        s.add_argument("--results", required=True)
    subs["variant"].add_argument("--name", choices=list(NEW), required=True)
    subs["boot"].add_argument("--key", choices=list(NEW), required=True)
    subs["boot"].add_argument("--start", type=int, required=True)
    subs["boot"].add_argument("--stop", type=int, required=True)
    subs["boot"].add_argument("--workers", type=int, default=2)
    a = ap.parse_args()
    {"make-variants": make_variants, "selftest": selftest, "bindcheck": r7.bindcheck, "variant": variant, "estimate": estimate,
     "boot": r7.boot, "report": report}[a.cmd](a)


if __name__ == "__main__":
    main()
